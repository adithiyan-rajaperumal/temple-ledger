export const DEFAULT_COUNTRY = 'India';
export const DEFAULT_STATE = 'Tamil Nadu';

export function getCountriesList(lang = 'en') {
  return COUNTRIES_DATA.map(c => ({
    code: c.code,
    name: c.nameEn,
    displayName: lang === 'ta' && c.nameTa ? `${c.nameTa} (${c.nameEn})` : c.nameEn
  }));
}

export function getStatesForCountry(countryName, lang = 'en') {
  if (!countryName) {
    countryName = DEFAULT_COUNTRY;
  }
  const countryObj = COUNTRIES_DATA.find(
    c => c.nameEn.toLowerCase() === countryName.toLowerCase() ||
         c.code.toLowerCase() === countryName.toLowerCase() ||
         (c.nameTa && c.nameTa === countryName)
  );

  if (!countryObj || !countryObj.states || countryObj.states.length === 0) {
    return [
      {
        name: 'General',
        displayName: lang === 'ta' ? 'பொதுவான பகுதி' : 'General / Main'
      }
    ];
  }

  return countryObj.states.map(s => ({
    name: s.nameEn,
    displayName: lang === 'ta' && s.nameTa ? `${s.nameTa} (${s.nameEn})` : s.nameEn
  }));
}
